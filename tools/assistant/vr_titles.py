import json
import mmap
import os
import re
from pathlib import Path

ROOTS = [Path(r"D:\AnyPS5 Games"), Path(r"D:\ps5 games dumps from ps5"), Path(r"C:\ps5 games dumps from ps5")]
OUT = Path(r"C:\AnyPS5 Games\_reports\vr-titles.md")
CACHE = Path(r"C:\AnyPS5 Games\_tools\live\vr-titles-cache.json")
VR_LIBS = [b"libSceHmd2", b"libSceVrTracker2", b"libSceHmd", b"libSceVrTracker", b"libSceVrSetupDialog", b"libSceHmdSetupDialog", b"libSceFaceTracker"]
RENDER = {"libSceHmd2"}
ID_RE = re.compile(r"\((PPSA\d{5}|CUSA\d{5})\)")


def title_of(folder):
    for p in (folder / "app0" / "sce_sys" / "param.json", folder / "sce_sys" / "param.json"):
        try:
            d = json.loads(p.read_text(encoding="utf-8-sig"))
        except (OSError, ValueError):
            continue
        loc = d.get("localizedParameters") or {}
        entry = loc.get(loc.get("defaultLanguage", ""), {}) if isinstance(loc, dict) else {}
        name = entry.get("titleName") if isinstance(entry, dict) else None
        return (name or folder.name), d.get("titleId") or ""
    return folder.name, ""


def binaries(folder):
    for base in (folder / "app0", folder):
        eboot = base / "eboot.bin"
        if eboot.is_file():
            yield eboot
            mod = base / "sce_module"
            if mod.is_dir():
                yield from (p for p in mod.iterdir() if p.suffix.lower() in (".prx", ".sprx"))
            return


def scan_file(path):
    found = set()
    try:
        with open(path, "rb") as f, mmap.mmap(f.fileno(), 0, access=mmap.ACCESS_READ) as m:
            for lib in VR_LIBS:
                i = m.find(lib)
                while i != -1:
                    nxt = m[i + len(lib):i + len(lib) + 1]
                    if nxt in (b".", b"\x00", b"_"):
                        found.add(lib.decode())
                        break
                    i = m.find(lib, i + 1)
    except (OSError, ValueError):
        pass
    return found


def folders():
    for root in ROOTS:
        if not root.is_dir():
            continue
        for d in sorted(root.iterdir()):
            if d.is_dir() and not d.name.startswith(("_", ".")):
                if (d / "app0" / "sce_sys" / "param.json").is_file() or (d / "sce_sys" / "param.json").is_file():
                    yield d


def main():
    cache = json.loads(CACHE.read_text(encoding="utf-8")) if CACHE.exists() else {}
    rows = {}
    for d in folders():
        bins = list(binaries(d))
        if not bins:
            continue
        key = str(d)
        stamp = max(int(b.stat().st_mtime) for b in bins)
        hit = cache.get(key)
        if hit and hit.get("stamp") == stamp:
            libs = set(hit["libs"])
        else:
            libs = set()
            for b in bins:
                libs |= scan_file(b)
            if "libSceHmd2" in libs:
                libs.discard("libSceHmd")
            if "libSceVrTracker2" in libs:
                libs.discard("libSceVrTracker")
            cache[key] = {"stamp": stamp, "libs": sorted(libs)}
        if not libs:
            continue
        title, tid = title_of(d)
        m = ID_RE.search(d.name)
        tid = tid or (m.group(1) if m else "")
        k = tid or title
        prev = rows.get(k)
        where = "game folder" if d.parent == ROOTS[0] else "dump"
        if prev:
            prev["where"].add(where)
            prev["libs"] |= libs
        else:
            rows[k] = {"title": title, "tid": tid, "libs": libs, "where": {where}}
    CACHE.parent.mkdir(parents=True, exist_ok=True)
    CACHE.write_text(json.dumps(cache, indent=1), encoding="utf-8")
    vr = sorted((r for r in rows.values() if r["libs"] & RENDER), key=lambda r: r["title"].lower())
    other = sorted((r for r in rows.values() if not r["libs"] & RENDER), key=lambda r: r["title"].lower())
    lines = ["# Games that use PS VR libraries",
             "",
             "Generated by `_tools\\assistant\\vr_titles.py` from every game folder and dump (nightly task \"AnyPS5 VR titles\"). Do not edit by hand.",
             "",
             "## PS VR2 games (link libSceHmd2: headset rendering)"]
    lines += [f"- {r['title']} ({r['tid']}): {', '.join(sorted(r['libs']))} [{', '.join(sorted(r['where']))}]" for r in vr] or ["- none"]
    lines += ["", "## Other games that link VR libraries (PS4-era PS VR libSceHmd/VrTracker, setup dialog, face tracking: usually unused at runtime; confirm with the import registry)"]
    lines += [f"- {r['title']} ({r['tid']}): {', '.join(sorted(r['libs']))} [{', '.join(sorted(r['where']))}]" for r in other] or ["- none"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(vr)} real VR games, {len(other)} flat games with VR helpers")
    for r in vr:
        print(" -", r["title"], r["tid"])


if __name__ == "__main__":
    main()
